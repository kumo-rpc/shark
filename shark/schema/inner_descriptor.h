    inline bool Descriptor::IsReservedName(ConstStringParam name) const {
        for (int i = 0; i < reserved_name_count(); i++) {
            if (name == static_cast<ConstStringParam>(reserved_name(i))) {
                return true;
            }
        }
        return false;
    }

