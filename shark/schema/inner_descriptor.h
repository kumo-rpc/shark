    inline SharkFieldType FieldDescriptor::type() const {
        if (type_once_) {
            internal::call_once(*type_once_, &FieldDescriptor::TypeOnceInit, this);
        }
        return static_cast<SharkFieldType>(type_);
    }

    inline bool FieldDescriptor::is_required() const {
        return label() == FieldLabel::REQUIRED;
    }

    inline bool FieldDescriptor::is_optional() const {
        return label() == FieldLabel::OPTIONAL;
    }

    inline bool FieldDescriptor::is_repeated() const {
        return label() == FieldLabel::REPEATED;
    }

    inline bool FieldDescriptor::is_packable() const {
        return is_repeated() && IsTypePackable(type());
    }

    inline bool FieldDescriptor::is_map() const {
        return type() == SharkFieldType::MESSAGE && is_map_message_type();
    }

    inline bool FieldDescriptor::has_optional_keyword() const {
        return proto3_optional_ || (file()->syntax() == SyntaxEdition::SYNTAX_PROTO2 && is_optional() && !containing_oneof());
    }

    inline const OneofDescriptor* FieldDescriptor::real_containing_oneof() const {
        auto* oneof = containing_oneof();
        return oneof && !oneof->is_synthetic() ? oneof : nullptr;
    }

    inline bool FieldDescriptor::has_presence() const {
        if (is_repeated())
            return false;
        return cpp_type() == SharkFieldCppType::CPPTYPE_MESSAGE || containing_oneof() || file()->syntax() == SyntaxEdition::SYNTAX_PROTO2;
    }

    // To save space, index() is computed by looking at the descriptor's position
    // in the parent's array of children.
    inline int FieldDescriptor::index() const {
        if (!is_extension_) {
            return static_cast<int>(this - containing_type()->fields_);
        } else if (extension_scope() != nullptr) {
            return static_cast<int>(this - extension_scope()->extensions_);
        } else {
            return static_cast<int>(this - file_->extensions_);
        }
    }

    inline int Descriptor::index() const {
        if (containing_type_ == nullptr) {
            return static_cast<int>(this - file_->message_types_);
        } else {
            return static_cast<int>(this - containing_type_->nested_types_);
        }
    }

    inline const FileDescriptor* OneofDescriptor::file() const {
        return containing_type()->file();
    }

    inline int OneofDescriptor::index() const {
        return static_cast<int>(this - containing_type_->oneof_decls_);
    }

    inline bool OneofDescriptor::is_synthetic() const {
        return field_count() == 1 && field(0)->proto3_optional_;
    }

    inline int EnumDescriptor::index() const {
        if (containing_type_ == nullptr) {
            return static_cast<int>(this - file_->enum_types_);
        } else {
            return static_cast<int>(this - containing_type_->enum_types_);
        }
    }

